// Builds src/girth-model.mjs: girths (cm) people of a given sex, height, weight and age usually have,
// so the 3D body looks like a real person when no tape measurements were entered.
//   ANSUR II (US Army anthropometric survey, public data; 1,986 women and 4,082 men, measured):
//     https://www.openlab.psu.edu/ansur2/  ->  work/ansur2/female.csv, work/ansur2/male.csv
//   Body fat for men: Kaggle fedesoriano/body-fat-prediction-dataset (252 men, underwater weighing)
//     -> how girths change with body fat at the same height, weight and age.
// Usage: node scripts/build-girth-model.mjs work/ansur2 <folder with bodyfat.csv>
import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';

const [ansurDir = 'work/ansur2', kaggleDir] = process.argv.slice(2);
if (!kaggleDir) throw Error('usage: node scripts/build-girth-model.mjs <ansur2 folder> <bodyfat.csv folder>');

const csv = file => {
  const [head, ...rows] = readFileSync(file, 'latin1').trim().split(/\r?\n/).map(l => l.split(','));
  return rows.filter(r => r.length === head.length).map(r => Object.fromEntries(head.map((h, i) => [h.trim(), r[i]])));
};
// Least squares with a tiny ridge; returns coefficients and RMSE.
function fit(X, y) {
  const k = X[0].length, A = Array.from({length: k}, () => new Array(k + 1).fill(0));
  X.forEach((x, n) => { for (let i = 0; i < k; i++) { for (let j = 0; j < k; j++) A[i][j] += x[i] * x[j]; A[i][k] += x[i] * y[n]; } });
  for (let i = 1; i < k; i++) A[i][i] += 1e-6;
  for (let c = 0; c < k; c++) { // Gauss-Jordan
    let p = c; for (let r = c + 1; r < k; r++) if (Math.abs(A[r][c]) > Math.abs(A[p][c])) p = r;
    [A[c], A[p]] = [A[p], A[c]];
    for (let r = 0; r < k; r++) if (r !== c) { const f = A[r][c] / A[c][c]; for (let j = c; j <= k; j++) A[r][j] -= f * A[c][j]; }
  }
  const b = A.map((row, i) => row[k] / row[i]);
  const rmse = Math.sqrt(X.reduce((s, x, n) => s + (x.reduce((t, v, i) => t + v * b[i], 0) - y[n]) ** 2, 0) / X.length);
  return {b: b.map(v => +v.toPrecision(6)), rmse: +rmse.toFixed(2)};
}
// Features: 1, height (cm), weight (kg), age, BMI.
const feats = (h, w, a) => [1, h, w, a, w / (h / 100) ** 2];

const GIRTHS = {chest: 'chestcircumference', waist: 'waistcircumference', hip: 'buttockcircumference', thigh: 'thighcircumference', calf: 'calfcircumference', arm: 'bicepscircumferenceflexed', neck: 'neckcircumference',
  // Cross-sections (cm): where the volume sits, not just how much there is.
  chestBreadth: 'chestbreadth', chestDepth: 'chestdepth', waistBreadth: 'waistbreadth', waistDepth: 'waistdepth', hipBreadth: 'hipbreadth', buttockDepth: 'buttockdepth',
  waistHeight: 'waistheightomphalion'};
const model = {};
for (const sex of ['female', 'male']) {
  const rows = csv(join(ansurDir, sex + '.csv')).map(r => ({h: r.stature / 10, w: r.weightkg / 10, a: +r.Age, g: Object.fromEntries(Object.entries(GIRTHS).map(([k, c]) => [k, r[c] / 10]))}))
    .filter(r => r.h > 130 && r.w > 30 && r.a > 0);
  const X = rows.map(r => feats(r.h, r.w, r.a)), m = {n: rows.length, range: {}, coef: {}, rmse: {}};
  for (const k of Object.keys(GIRTHS)) { const f = fit(X, rows.map(r => r.g[k])); m.coef[k] = f.b; m.rmse[k] = f.rmse; }
  for (const [k, v] of [['h', 'height'], ['w', 'weight'], ['a', 'age']]) { const s = rows.map(r => r[k]).sort((a, b) => a - b); m.range[v] = [s[Math.floor(s.length * 0.005)], s[Math.floor(s.length * 0.995)]].map(x => +x.toFixed(1)); }
  model[sex] = m;
}

// Men: girth change per body-fat point at the same height, weight and age (Kaggle), plus the usual body fat.
{
  const rows = csv(join(kaggleDir, 'bodyfat.csv')).map(r => ({h: r.Height * 2.54, w: r.Weight * 0.45359, a: +r.Age, fat: +r.BodyFat,
    g: {chest: +r.Chest, waist: +r.Abdomen, hip: +r.Hip, thigh: +r.Thigh, arm: +r.Biceps}})).filter(r => r.h > 150 && r.fat > 2);
  const fatHat = fit(rows.map(r => feats(r.h, r.w, r.a)), rows.map(r => r.fat));
  const perFat = {};
  for (const k of ['chest', 'waist', 'hip', 'thigh', 'arm']) perFat[k] = +fit(rows.map(r => [...feats(r.h, r.w, r.a), r.fat]), rows.map(r => r.g[k])).b[5].toFixed(3);
  model.male.fat = {n: rows.length, expected: fatHat.b, rmse: fatHat.rmse, perPoint: perFat};
}

writeFileSync('src/girth-model.mjs', `// Generated by scripts/build-girth-model.mjs. Girths in cm from sex, height (cm), weight (kg), age and body fat.
// Sources: ANSUR II public data (US Army, 2012; 1,986 women, 4,082 men) and, for the effect of body fat in men,
// Kaggle fedesoriano/body-fat-prediction-dataset (252 men, underwater weighing). Coefficients: [1, height, weight, age, BMI].
export const GIRTH_MODEL = ${JSON.stringify(model)};
const clamp = (v, [a, b]) => Math.min(b, Math.max(a, v));

// Tape measures (cm) a typical person with these numbers has. arm: relaxed upper arm (ANSUR measures it flexed, ~1.5 cm more).
const TAPE = ['chest', 'waist', 'hip', 'thigh', 'calf', 'arm'];
export function predictGirths(r) {
  const g = predictShape(r);
  return Object.fromEntries(TAPE.filter(k => k in g).map(k => [k, g[k]]));
}
// Tape measures plus cross-sections (chest/waist breadth and depth, hip breadth, buttock depth) and the navel height (cm).
export function predictShape({sex, height, weight, age, body_fat: fat}) {
  if (!height || !weight) return {};
  const m = GIRTH_MODEL[sex === 'female' ? 'female' : 'male'], h = clamp(height, m.range.height), w = clamp(weight, m.range.weight), a = clamp(age || 30, m.range.age);
  const x = [1, h, w, a, w / (h / 100) ** 2], dot = c => c.reduce((s, v, i) => s + v * x[i], 0);
  const g = Object.fromEntries(Object.entries(m.coef).map(([k, c]) => [k, dot(c)]));
  g.arm -= 1.5;
  if (fat != null && m.fat) {
    // Men: more (or less) fat than usual for this height and weight -> girths shift by the measured effect.
    const extra = Math.max(-12, Math.min(12, fat - dot(m.fat.expected)));
    for (const [k, per] of Object.entries(m.fat.perPoint)) g[k] += per * extra;
  } else if (fat != null) {
    // Women: the US Navy body-fat formula ties waist + hip - neck to body fat and height. Use only the difference between
    // this body fat and the usual one for this BMI and age (Deurenberg 1991), so the formula's own offset cancels out.
    const inch = 2.54, sum = f => 10 ** ((f + 78.387 + 97.684 * Math.log10(h / inch)) / 163.205) * inch;
    const usual = 1.2 * x[4] + 0.23 * a - 5.4, gap = Math.max(-15, Math.min(15, sum(fat) - sum(usual)));
    g.waist += gap * 0.6; g.hip += gap * 0.4;
  }
  // Cross-sections follow their girth's body-fat shift in proportion.
  const base = Object.fromEntries(Object.entries(m.coef).map(([k, c]) => [k, dot(c)]));
  for (const [ring, parts] of [['chest', ['chestBreadth', 'chestDepth']], ['waist', ['waistBreadth', 'waistDepth']], ['hip', ['hipBreadth', 'buttockDepth']]])
    for (const k of parts) g[k] *= g[ring] / base[ring];
  delete g.neck;
  return Object.fromEntries(Object.entries(g).map(([k, v]) => [k, Math.round(v * 10) / 10]));
}
`);
for (const sex of ['female', 'male']) console.log(sex, model[sex].n, 'rows; RMSE cm', JSON.stringify(model[sex].rmse), 'ranges', JSON.stringify(model[sex].range));
console.log('men fat effect (cm per % fat):', JSON.stringify(model.male.fat.perPoint), 'expected-fat RMSE', model.male.fat.rmse);

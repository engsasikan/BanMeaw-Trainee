// Builds dist/exercise-media.mjs: which library exercises have an ExerciseDB demo GIF.
// Only names and ExerciseDB ids are stored. The GIFs are not copied; the app links to them on
// ExerciseDB's own server (static.exercisedb.dev) and credits ExerciseDB under the picture.
//   node scripts/build-exercise-media.mjs
import {writeFileSync} from 'node:fs';
import {LIBRARY} from '../dist/exercise-library.mjs';
import {mediaKey} from '../dist/exercise-media-key.mjs';

const API = 'https://oss.exercisedb.dev/api/v1/exercises';
const wait = ms => new Promise(r => setTimeout(r, ms));

// The free API rate-limits quickly: page slowly and back off on 429.
async function page(after) {
 for (let attempt = 0; attempt < 8; attempt++) {
  const res = await fetch(`${API}?limit=25${after ? '&after=' + encodeURIComponent(after) : ''}`);
  if (res.ok) return res.json();
  if (res.status !== 429 && res.status < 500) throw new Error(`ExerciseDB ${res.status}`);
  await wait(5000 * (attempt + 1));
 }
 throw new Error('ExerciseDB kept refusing requests; try again later');
}

const all = [];
for (let after = '';;) {
 const {data, meta} = await page(after);
 all.push(...data);
 if (!meta?.hasNextPage) break;
 after = meta.nextCursor;
 await wait(1200);
}

const ids = new Map(all.map(e => [mediaKey(e.name), e.exerciseId]));
const map = {};
for (const [name] of LIBRARY) {
 const id = ids.get(mediaKey(name));
 if (id && /^[A-Za-z0-9]+$/.test(id)) map[mediaKey(name)] = id;
}

writeFileSync('dist/exercise-media.mjs', `// Generated by scripts/build-exercise-media.mjs from the free ExerciseDB API (${API}).
// Library exercise name (normalised) -> ExerciseDB id. GIFs stay on ExerciseDB's server.
import {mediaKey} from './exercise-media-key.mjs?v=1';
export const GIF_IDS=${JSON.stringify(map)};
export function gifFor(name){const id=GIF_IDS[mediaKey(name)];return id?'https://static.exercisedb.dev/media/'+id+'.gif':null;}
`);
console.log(`ExerciseDB: ${all.length} exercises, ${Object.keys(map).length} of ${LIBRARY.length} library names matched`);

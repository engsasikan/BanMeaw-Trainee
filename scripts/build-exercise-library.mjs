// Builds dist/exercise-library.mjs from hasaneyldrm/exercises-dataset (names and muscle data, MIT).
// The dataset's images/GIFs are © Gym visual and are NOT used.
//   git clone --depth 1 https://github.com/hasaneyldrm/exercises-dataset.git work/exercises-dataset
//   node scripts/build-exercise-library.mjs [path/to/exercises-dataset]
import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';

const root = process.argv[2] || 'work/exercises-dataset';
const data = JSON.parse(readFileSync(join(root, 'data/exercises.json'), 'utf8'));

const GROUP = {waist: 'ท้อง', 'upper legs': 'ขา', back: 'หลัง', 'lower legs': 'น่อง', chest: 'อก', 'upper arms': 'แขน', cardio: 'คาร์ดิโอ',
 shoulders: 'ไหล่', 'lower arms': 'แขนท่อนล่าง', neck: 'คอ'};
const EQUIPMENT = {'body weight': 'น้ำหนักตัว', cable: 'เคเบิล', 'leverage machine': 'เครื่อง', assisted: 'เครื่องช่วย', 'medicine ball': 'เมดิซินบอล',
 'stability ball': 'ลูกบอล', band: 'ยางยืด', barbell: 'บาร์เบล', rope: 'เชือก', dumbbell: 'ดัมเบล', 'ez barbell': 'บาร์ EZ', 'sled machine': 'เครื่องสเลด',
 'upper body ergometer': 'เครื่องปั่นแขน', kettlebell: 'เคตเทิลเบล', 'olympic barbell': 'บาร์เบล', weighted: 'ถ่วงน้ำหนัก', 'bosu ball': 'โบสุบอล',
 'resistance band': 'ยางยืด', roller: 'โฟมโรลเลอร์', 'skierg machine': 'เครื่องสกี', hammer: 'ค้อน', 'smith machine': 'สมิธแมชชีน', 'wheel roller': 'ล้อกลิ้ง',
 'stationary bike': 'จักรยาน', tire: 'ยางรถ', 'trap bar': 'แทรปบาร์', 'elliptical machine': 'เครื่องเดินวงรี', 'stepmill machine': 'เครื่องขึ้นบันได'};
// Dataset muscle names -> 3D model base muscles (see exercise-muscles.mjs).
const MUSCLE = {abs: ['abs'], quads: ['quad'], lats: ['lat'], calves: ['calf'], pectorals: ['pec'], glutes: ['glute'], hamstrings: ['hamstring'],
 adductors: ['adductor'], triceps: ['triceps'], spine: ['erector'], 'upper back': ['lat', 'trap'], biceps: ['biceps'], delts: ['deltoid'],
 forearms: ['flexor'], traps: ['trap'], 'serratus anterior': ['serratus'], abductors: ['glute'], 'levator scapulae': ['trap'],
 obliques: ['oblique'], shoulders: ['deltoid'], quadriceps: ['quad'], chest: ['pec'], 'lower back': ['erector'], trapezius: ['trap'],
 deltoids: ['deltoid'], core: ['abs'], rhomboids: ['trap'], 'rotator cuff': ['deltoid'], 'wrist flexors': ['flexor'], 'wrist extensors': ['flexor'],
 'latissimus dorsi': ['lat'], abdominals: ['abs'], soleus: ['calf'], wrists: ['flexor'], hands: ['flexor']};
const LABEL = {pec: 'อก', deltoid: 'ไหล่', biceps: 'ต้นแขนหน้า หน้าแขน', triceps: 'ต้นแขนหลัง หลังแขน', flexor: 'แขนท่อนล่าง', trap: 'บ่า', lat: 'ปีกหลัง',
 erector: 'หลังล่าง', abs: 'หน้าท้อง', oblique: 'ข้างท้อง', serratus: 'ซี่โครงข้าง', glute: 'ก้น', quad: 'ต้นขาหน้า หน้าขา', hamstring: 'ต้นขาหลัง หลังขา',
 adductor: 'ต้นขาด้านใน', calf: 'น่อง', tibialis: 'หน้าแข้ง'};

const title = s => s.replace(/\s*\((male|female)\)/g, '').trim().split(/\s+/).map(w => w[0].toUpperCase() + w.slice(1)).join(' ');
const muscles = list => [...new Set(list.flatMap(m => MUSCLE[m] || []))];
const seen = new Set(), rows = [];
for (const x of data) {
 const name = title(x.name);
 if (seen.has(name.toLowerCase())) continue;
 seen.add(name.toLowerCase());
 const primary = muscles([x.target]);
 const secondary = muscles([x.muscle_group, ...(x.secondary_muscles || [])]).filter(m => !primary.includes(m));
 const group = GROUP[x.category] || x.category;
 const aliases = [EQUIPMENT[x.equipment] || '', x.target, ...primary.map(m => LABEL[m])].filter(Boolean).join(' ');
 rows.push([name, group, aliases, primary.join(' '), secondary.join(' ')]);
}
rows.sort((a, b) => a[0].localeCompare(b[0]));

writeFileSync('dist/exercise-library.mjs',
 `// Generated by scripts/build-exercise-library.mjs from https://github.com/hasaneyldrm/exercises-dataset
// Exercise names and muscle data: MIT License, Copyright (c) 2026 Hasan Emir Yıldırım.
// [name, group, search aliases, primary muscles, secondary muscles]
export const LIBRARY=[\n${rows.map(r => JSON.stringify(r)).join(',\n')}\n];\n`);
console.log(rows.length, 'exercises written to dist/exercise-library.mjs');
